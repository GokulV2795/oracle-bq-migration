# MAIN
# ============================================================

def main():

    print()
    print("=" * 70)
    print(
        "GCS → BIGQUERY RAW LOAD"
    )
    print("=" * 70)

    print(
        f"Project       : {PROJECT_ID}"
    )

    print(
        f"GCS bucket    : {GCS_BUCKET}"
    )

    print(
        f"BQ dataset    : {BQ_DATASET}"
    )

    print(
        f"BQ control    : {BQ_CONTROL_DATASET}"
    )

    print(
        f"BQ location   : {BQ_LOCATION}"
    )

    print(
        f"Started       : "
        f"{datetime.now(timezone.utc).isoformat()}"
    )

    print("=" * 70)

    storage_client = storage.Client(
        project=PROJECT_ID
    )

    bq_client = bigquery.Client(
        project=PROJECT_ID
    )

    successful = 0
    failed = 0

    # --------------------------------------------------------
    # Determine ONE latest run
    # --------------------------------------------------------

    run_ids = []

    for table_name in TABLES:

        run_id = get_latest_run_id(
            storage_client,
            table_name,
        )

        if run_id:

            run_ids.append(
                run_id
            )

    if not run_ids:

        raise RuntimeError(
            "No extraction runs found in GCS."
        )

    latest_run_id = sorted(
        set(run_ids)
    )[-1]

    print()
    print(
        f"Latest extraction run : "
        f"{latest_run_id}"
    )

    print()

    # --------------------------------------------------------
    # Process all tables using SAME run_id
    # --------------------------------------------------------

    for table_name in TABLES:

        try:

            # ------------------------------------------------
            # Verify this table belongs to the same run
            # ------------------------------------------------

            table_run_id = get_latest_run_id(
                storage_client,
                table_name,
            )

            if not table_run_id:

                print(
                    f"SKIPPING {table_name}: "
                    f"no extraction run found"
                )

                continue

            if table_run_id != latest_run_id:

                raise RuntimeError(
                    f"Run ID mismatch for "
                    f"{table_name}. "
                    f"Expected {latest_run_id}, "
                    f"found {table_run_id}"
                )

            load_table(
                table_name,
                latest_run_id,
                storage_client,
                bq_client,
            )

            successful += 1

        except Exception as exc:

            failed += 1

            print()
            print(
                "=" * 70
            )

            print(
                f"FAILED TABLE: "
                f"{table_name}"
            )

            print(
                f"RUN ID      : "
                f"{latest_run_id}"
            )

            print(
                f"ERROR       : "
                f"{exc}"
            )

            print(
                "=" * 70
            )

    # ========================================================
    # SUMMARY
    # ========================================================

    print()
    print("=" * 70)
    print(
        "LOAD SUMMARY"
    )
    print("=" * 70)

    print(
        f"Run ID            : "
        f"{latest_run_id}"
    )

    print(
        f"Successful tables : "
        f"{successful}"
    )

    print(
        f"Failed tables     : "
        f"{failed}"
    )

    print("=" * 70)


if __name__ == "__main__":
    main()