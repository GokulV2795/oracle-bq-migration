# ============================================================
# IDENTIFIER VALIDATION
# ============================================================

def validate_identifier(value: str) -> str:

    if not re.fullmatch(
        r"[A-Za-z0-9_]+",
        value,
    ):
        raise ValueError(
            f"Invalid identifier: {value}"
        )

    return value


# ============================================================
# LATEST RUN ID
# ============================================================

def get_latest_run_id(
    storage_client: storage.Client,
    table_name: str,
):
    """
    Find the latest run_id available for a table.

    Run IDs use:
        YYYYMMDD_HHMMSS

    Therefore lexical sorting works.
    """

    table_name = validate_identifier(
        table_name
    )

    bucket = storage_client.bucket(
        GCS_BUCKET
    )

    prefix = (
        f"oracle/raw/{table_name}/"
    )

    blobs = bucket.list_blobs(
        prefix=prefix
    )

    run_ids = set()

    pattern = re.compile(
        rf"oracle/raw/{table_name}/"
        r"extract_date=[^/]+/"
        r"run_id=([^/]+)/"
    )

    for blob in blobs:

        match = pattern.search(
            blob.name
        )

        if match:
            run_ids.add(
                match.group(1)
            )

    if not run_ids:
        return None

    return sorted(run_ids)[-1]


# ============================================================
# EXACT PARQUET FILES
# ============================================================

def get_run_files(
    storage_client: storage.Client,
    table_name: str,
    run_id: str,
):
    """
    Discover exact Parquet objects belonging
    to a particular table and run.
    """

    table_name = validate_identifier(
        table_name
    )

    bucket = storage_client.bucket(
        GCS_BUCKET
    )

    prefix = (
        f"oracle/raw/{table_name}/"
    )

    blobs = bucket.list_blobs(
        prefix=prefix
    )

    parquet_files = []

    pattern = re.compile(
        rf"oracle/raw/{table_name}/"
        r"extract_date=[^/]+/"
        rf"run_id={re.escape(run_id)}/"
        r".+\.parquet$"
    )

    for blob in blobs:

        if pattern.fullmatch(
            blob.name
        ):

            parquet_files.append(
                f"gs://{GCS_BUCKET}/{blob.name}"
            )

    parquet_files.sort()

    return parquet_files


# ============================================================
# EXTRACTION AUDIT
# ============================================================

def get_extraction_audit(
    storage_client: storage.Client,
    table_name: str,
    run_id: str,
):
    """
    Read the extraction audit JSON generated by
    oracle_to_gcs.py.

    This is the source of truth for:

        FULL / INCREMENTAL
        watermark column
        current watermark
        extraction status
    """

    table_name = validate_identifier(
        table_name
    )

    extract_date = (
        f"{run_id[0:4]}-"
        f"{run_id[4:6]}-"
        f"{run_id[6:8]}"
    )

    audit_object = (
        f"audit/extraction/"
        f"extract_date={extract_date}/"
        f"run_id={run_id}/"
        f"{table_name}.json"
    )

    print(
        f"Reading extraction audit:"
    )
    print(
        f"  gs://{GCS_BUCKET}/{audit_object}"
    )

    bucket = storage_client.bucket(
        GCS_BUCKET
    )

    blob = bucket.blob(
        audit_object
    )

    if not blob.exists():

        raise FileNotFoundError(
            "Extraction audit not found: "
            f"gs://{GCS_BUCKET}/{audit_object}"
        )

    content = blob.download_as_text()

    audit = json.loads(content)

    return audit


# ============================================================
# GET LOAD METADATA
# ============================================================

def get_load_metadata(
    storage_client: storage.Client,
    table_name: str,
    run_id: str,
):
    """
    Extract load metadata from the extraction audit.
    """

    audit = get_extraction_audit(
        storage_client,
        table_name,
        run_id,
    )

    load_type = audit.get(
        "load_type"
    )

    watermark_column = audit.get(
        "watermark_column"
    )

    current_watermark = audit.get(
        "current_watermark"
    )

    status = audit.get(
        "status"
    )

    if not load_type:

        raise ValueError(
            f"Extraction audit for {table_name} "
            f"does not contain load_type."
        )

    if status != "SUCCESS":

        raise RuntimeError(
            f"Extraction for {table_name} "
            f"is not successful. "
            f"Audit status={status}"
        )

    load_type = str(
        load_type
    ).upper()

    if load_type not in {
        "FULL",
        "INCREMENTAL",
    }:

        raise ValueError(
            f"Unsupported load_type "
            f"'{load_type}' for {table_name}"
        )

    print(
        f"Load type from audit : {load_type}"
    )

    print(
        f"Watermark column     : "
        f"{watermark_column}"
    )

    print(
        f"Current watermark    : "
        f"{current_watermark}"
    )

    return {
        "load_type": load_type,
        "watermark_column": watermark_column,
        "current_watermark": current_watermark,
        "status": status,
    }


# ============================================================
# TEMP TABLE NAME
# ============================================================

def get_temp_table_name(
    table_name: str,
    run_id: str,
) -> str:

    table_name = validate_identifier(
        table_name
    )

    safe_run_id = re.sub(
        r"[^A-Za-z0-9_]",
        "_",
        run_id,
    )

    return (
        f"{table_name}"
        f"__CDC_{safe_run_id}"
    )


# ============================================================
# FULL LOAD
# ============================================================

def load_full_table(
    table_name: str,
    run_id: str,
    parquet_files,
    bq_client: bigquery.Client,
):
    """
    FULL load:
        GCS → BigQuery RAW

    Existing RAW table is completely replaced.
    """

    destination_table = (
        f"{PROJECT_ID}."
        f"{BQ_DATASET}."
        f"{table_name}"
    )

    print()
    print("-" * 70)
    print(
        f"FULL LOAD : {table_name}"
    )
    print(
        f"Run ID    : {run_id}"
    )
    print(
        f"Target    : {destination_table}"
    )
    print("-" * 70)

    job_config = bigquery.LoadJobConfig(
        source_format=(
            bigquery.SourceFormat.PARQUET
        ),
        write_disposition=(
            bigquery.WriteDisposition.WRITE_TRUNCATE
        ),
        autodetect=True,
    )

    load_job = (
        bq_client.load_table_from_uri(
            parquet_files,
            destination_table,
            job_config=job_config,
            location=BQ_LOCATION,
        )
    )

    load_job.result()

    table = bq_client.get_table(
        destination_table
    )

    print(
        f"Loaded rows    : {table.num_rows}"
    )

    print(
        f"Loaded columns : {len(table.schema)}"
    )

    print(
        "Load type      : FULL"
    )

    print(
        "Status         : SUCCESS"
    )

    return table.num_rows


