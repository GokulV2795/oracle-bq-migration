# ============================================================
# MERGE
# ============================================================

def merge_incremental(
    table_name: str,
    temp_table: str,
    bq_client: bigquery.Client,
):
    """
    MERGE incremental records into RAW.

    Existing PK:
        UPDATE

    New PK:
        INSERT
    """

    table_name = validate_identifier(
        table_name
    )

    primary_key = PRIMARY_KEYS.get(
        table_name
    )

    if not primary_key:

        raise ValueError(
            f"No primary key configured "
            f"for {table_name}"
        )

    target_table = (
        f"`{PROJECT_ID}."
        f"{BQ_DATASET}."
        f"{table_name}`"
    )

    source_table = (
        f"`{temp_table}`"
    )

    print()
    print("-" * 70)
    print(
        f"MERGE : {table_name}"
    )
    print(
        f"Primary key : {primary_key}"
    )
    print(
        f"Target      : {target_table}"
    )
    print(
        f"Source      : {source_table}"
    )
    print("-" * 70)

    target = bq_client.get_table(
        f"{PROJECT_ID}."
        f"{BQ_DATASET}."
        f"{table_name}"
    )

    columns = [
        field.name
        for field in target.schema
    ]

    if primary_key not in columns:

        raise ValueError(
            f"Primary key {primary_key} "
            f"not found in "
            f"{table_name}"
        )

    # --------------------------------------------------------
    # UPDATE
    # --------------------------------------------------------

    update_columns = [
        column
        for column in columns
        if column != primary_key
    ]

    if update_columns:

        update_clause = ",\n".join(
            f"        T.`{column}` = "
            f"S.`{column}`"
            for column in update_columns
        )

    else:

        update_clause = (
            f"        T.`{primary_key}` = "
            f"S.`{primary_key}`"
        )

    # --------------------------------------------------------
    # INSERT
    # --------------------------------------------------------

    column_list = ", ".join(
        f"`{column}`"
        for column in columns
    )

    source_column_list = ", ".join(
        f"S.`{column}`"
        for column in columns
    )

    # --------------------------------------------------------
    # MERGE
    # --------------------------------------------------------

    merge_sql = f"""
    MERGE {target_table} AS T

    USING {source_table} AS S

    ON T.`{primary_key}` = S.`{primary_key}`

    WHEN MATCHED THEN
      UPDATE SET
{update_clause}

    WHEN NOT MATCHED THEN
      INSERT ({column_list})
      VALUES ({source_column_list})
    """

    print(
        "Executing MERGE..."
    )

    merge_job = bq_client.query(
        merge_sql,
        location=BQ_LOCATION,
    )

    merge_job.result()

    print(
        "MERGE status : SUCCESS"
    )

    return merge_job


# ============================================================
# DROP TEMP TABLE
# ============================================================

def drop_temp_table(
    temp_table: str,
    bq_client: bigquery.Client,
):

    print(
        f"Dropping temporary table : "
        f"{temp_table}"
    )

    bq_client.delete_table(
        temp_table,
        not_found_ok=True,
    )

    print(
        "Temporary table cleanup : SUCCESS"
    )


# ============================================================
# WATERMARK COMMIT
# ============================================================

def commit_watermark(
    table_name: str,
    run_id: str,
    watermark_column: str,
    current_watermark,
    bq_client: bigquery.Client,
):
    """
    Commit the extraction watermark only after
    the corresponding RAW load has succeeded.

    The extractor remains READ ONLY.

    This function is the downstream commit boundary.
    """

    if not current_watermark:

        print(
            f"No current watermark for "
            f"{table_name}; "
            f"watermark commit skipped."
        )

        return

    control_table = (
        f"`{PROJECT_ID}."
        f"{BQ_CONTROL_DATASET}."
        f"watermarks`"
    )

    print()
    print("-" * 70)
    print(
        f"COMMIT WATERMARK : "
        f"{table_name}"
    )
    print(
        f"Watermark column : "
        f"{watermark_column}"
    )
    print(
        f"New watermark    : "
        f"{current_watermark}"
    )
    print(
        f"Run ID           : "
        f"{run_id}"
    )
    print("-" * 70)

    query = f"""
    UPDATE {control_table}
    SET
        last_watermark = TIMESTAMP(@current_watermark),
        current_watermark = TIMESTAMP(@current_watermark),
        last_run_id = @run_id,
        status = 'COMMITTED',
        updated_at = CURRENT_TIMESTAMP()
    WHERE
        source_system = 'ORACLE'
        AND source_table = @source_table
        AND watermark_column = @watermark_column
    """

    job_config = bigquery.QueryJobConfig(
        query_parameters=[
            bigquery.ScalarQueryParameter(
                "current_watermark",
                "STRING",
                str(current_watermark),
            ),
            bigquery.ScalarQueryParameter(
                "run_id",
                "STRING",
                run_id,
            ),
            bigquery.ScalarQueryParameter(
                "source_table",
                "STRING",
                table_name,
            ),
            bigquery.ScalarQueryParameter(
                "watermark_column",
                "STRING",
                watermark_column,
            ),
        ]
    )

    query_job = bq_client.query(
        query,
        job_config=job_config,
        location=BQ_LOCATION,
    )

    query_job.result()

    if query_job.num_dml_affected_rows != 1:

        raise RuntimeError(
            f"Watermark commit failed for "
            f"{table_name}. "
            f"Expected 1 row updated, "
            f"affected="
            f"{query_job.num_dml_affected_rows}"
        )

    print(
        "Watermark commit : SUCCESS"
    )


# ============================================================
# LOAD ONE TABLE
# ============================================================

def load_table(
    table_name: str,
    run_id: str,
    storage_client: storage.Client,
    bq_client: bigquery.Client,
):
    """
    Process one table.

    Flow:

        Read audit
             ↓
        FULL / INCREMENTAL
             ↓
        Load RAW
             ↓
        Commit watermark
    """

    table_name = validate_identifier(
        table_name
    )

    print()
    print("=" * 70)
    print(
        f"Loading table : {table_name}"
    )
    print(
        f"Run ID        : {run_id}"
    )
    print("=" * 70)

    # --------------------------------------------------------
    # Read extraction metadata
    # --------------------------------------------------------

    metadata = get_load_metadata(
        storage_client,
        table_name,
        run_id,
    )

    load_type = metadata[
        "load_type"
    ]

    watermark_column = metadata[
        "watermark_column"
    ]

    current_watermark = metadata[
        "current_watermark"
    ]

    # --------------------------------------------------------
    # Get exact GCS files
    # --------------------------------------------------------

    parquet_files = get_run_files(
        storage_client,
        table_name,
        run_id,
    )

    if not parquet_files:

        raise FileNotFoundError(
            f"No Parquet files found for "
            f"{table_name}, "
            f"run_id={run_id}"
        )

    print()
    print("GCS files:")

    for uri in parquet_files:

        print(
            f"  {uri}"
        )

    # ========================================================
    # FULL
    # ========================================================

    if load_type == "FULL":

        load_full_table(
            table_name,
            run_id,
            parquet_files,
            bq_client,
        )

    # ========================================================
    # INCREMENTAL
    # ========================================================

    elif load_type == "INCREMENTAL":

        temp_table = None

        try:

            temp_table, incremental_rows = (
                load_incremental_to_temp(
                    table_name,
                    run_id,
                    parquet_files,
                    bq_client,
                )
            )

            # ------------------------------------------------
            # If there are no rows, no MERGE is required.
            # ------------------------------------------------

            if incremental_rows > 0:

                merge_incremental(
                    table_name,
                    temp_table,
                    bq_client,
                )

            else:

                print(
                    "No incremental rows. "
                    "MERGE skipped."
                )

        finally:

            if temp_table:

                drop_temp_table(
                    temp_table,
                    bq_client,
                )

    else:

        raise ValueError(
            f"Unsupported load type: "
            f"{load_type}"
        )

    # ========================================================
    # VALIDATE FINAL RAW TABLE
    # ========================================================

    destination_table = (
        f"{PROJECT_ID}."
        f"{BQ_DATASET}."
        f"{table_name}"
    )

    final_table = bq_client.get_table(
        destination_table
    )

    print()
    print(
        f"Final RAW rows : "
        f"{final_table.num_rows}"
    )

    print(
        f"Final columns  : "
        f"{len(final_table.schema)}"
    )

    # ========================================================
    # WATERMARK COMMIT
    # ========================================================

    commit_watermark(
        table_name=table_name,
        run_id=run_id,
        watermark_column=watermark_column,
        current_watermark=current_watermark,
        bq_client=bq_client,
    )

    print()
    print(
        f"TABLE STATUS : SUCCESS"
    )

    return final_table.num_rows


